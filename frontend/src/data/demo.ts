export function monthlyEstimate(property: Property) {
  return property.expenses
    .filter((line) => line.cadence === "monthly")
    .reduce((sum, line) => sum + line.amount, 0);
}

export function getProperty(id: string) {
  return properties.find((item) => item.id === id);
}

export function getOwner(id: string) {
  return owners.find((item) => item.id === id);
}
